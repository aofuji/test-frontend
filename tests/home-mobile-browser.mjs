import assert from 'node:assert/strict'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
const page = await browser.newPage({ viewport: { width: 375, height: 844 } })
const base = process.env.HOME_TEST_URL || 'http://127.0.0.1:5173'
const cards = page.locator('#catalogo article')
const bottomNav = page.getByRole('navigation', { name: 'Navegação inferior' })

try {
  await page.goto(base)
  await cards.first().waitFor()
  for (const width of [375, 390]) {
    await page.setViewportSize({ width, height: 844 })
    assert.equal(await page.locator('.desktop-header-row').isVisible(), false)
    assert.equal(await bottomNav.isVisible(), true)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    const hero = await page.getByRole('region', { name: 'Apresentação da Kurio' }).boundingBox()
    const image = await page.locator('.home-hero-art').boundingBox()
    assert.equal(hero.height, 190)
    assert(image.x > hero.x + hero.width / 2 && image.y + image.height < hero.y + hero.height)
    const first = await cards.nth(0).boundingBox(), second = await cards.nth(1).boundingBox()
    assert(second.x > first.x, 'Catalog must retain two columns')
    assert.equal(await bottomNav.locator('a[aria-current="page"]').count(), 1)
  }

  await page.goto(`${base}/?sort=price-asc&category=art&page=2&scenario=normal`)
  const search = page.getByRole('searchbox', { name: 'Buscar NFTs pelo nome' })
  await search.fill('Aurora')
  await search.press('Enter')
  await page.waitForURL((url) => url.searchParams.get('q') === 'Aurora' && url.searchParams.get('page') === '1')
  assert.equal(new URL(page.url()).searchParams.get('category'), 'art')
  assert.equal(new URL(page.url()).searchParams.get('sort'), 'price-asc')
  assert.equal(new URL(page.url()).hash, '#catalogo')
  await page.waitForFunction(() => document.querySelectorAll('#catalogo article').length === 1)

  await page.getByRole('button', { name: 'Abrir filtros' }).click()
  const filters = page.getByRole('dialog', { name: 'Filtros e ordenação', exact: true })
  await filters.waitFor()
  await filters.getByRole('slider', { name: 'Preço mínimo em ETH' }).press('ArrowRight')
  await filters.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await page.waitForURL((url) => url.searchParams.get('minPrice') === '0.33')
  assert.equal(await filters.isVisible(), true)
  await filters.getByRole('combobox', { name: 'Ordenar por' }).click()
  await page.getByRole('option', { name: 'Maior preço', exact: true }).click()
  await page.waitForURL((url) => url.searchParams.get('sort') === 'price-desc')
  await page.keyboard.press('Escape')
  await filters.waitFor({ state: 'hidden' })
  assert(await page.getByRole('button', { name: 'Abrir filtros' }).evaluate((element) => element === document.activeElement))

  await bottomNav.getByRole('link', { name: 'Favoritos', exact: true }).click()
  await page.waitForURL((url) => url.pathname === '/login')
  assert.equal(new URL(page.url()).searchParams.get('redirect'), '/#favoritos')
  await page.getByLabel('E-mail', { exact: true }).fill('ada@example.com')
  await page.getByLabel('Senha', { exact: true }).fill('collector123')
  await page.getByRole('main').getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForURL((url) => url.pathname === '/' && url.hash === '#favoritos')
  const favorites = page.getByRole('dialog', { name: 'Favoritos', exact: true })
  await favorites.getByText(/Você ainda não tem NFTs favoritos/).waitFor()
  await favorites.getByRole('button', { name: 'Fechar favoritos' }).click()
  await favorites.waitFor({ state: 'hidden' })

  await page.goto(`${base}/nft/aurora-001`)
  assert.equal(await bottomNav.count(), 0, 'Other screens must retain their existing layout')
  const addFavorite = page.getByRole('button', { name: 'Adicionar Aurora Chain #001 aos favoritos: Favoritar', exact: true })
  await addFavorite.click()
  await page.getByRole('button', { name: 'Remover Aurora Chain #001 dos favoritos: Favoritado', exact: true }).waitFor()
  await page.goto(base)
  await bottomNav.getByRole('link', { name: 'Favoritos', exact: true }).click()
  await favorites.getByRole('heading', { name: 'Aurora Chain #001', exact: true }).waitFor()
  assert.equal(await page.locator('#home-mobile-favorites').getAttribute('aria-current'), 'page')
  await favorites.getByRole('button', { name: 'Fechar favoritos' }).click()
  await favorites.waitFor({ state: 'hidden' })

  await bottomNav.getByRole('link', { name: /Carrinho/ }).click()
  await page.waitForURL((url) => url.pathname === '/cart')
  assert.equal(await bottomNav.count(), 0)
  await page.goto(base)
  await bottomNav.getByRole('link', { name: 'Perfil', exact: true }).click()
  await page.waitForURL((url) => url.pathname === '/profile')
  assert.equal(await bottomNav.count(), 0)

  await page.goto(base)
  await cards.first().waitFor()
  await page.evaluate(() => scrollTo(0, document.documentElement.scrollHeight))
  const footer = await page.getByRole('contentinfo').boundingBox(), nav = await bottomNav.boundingBox()
  assert(footer.y + footer.height <= nav.y, 'Bottom navigation must not cover the end of the content')
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.desktop-header-row')).display !== 'none')
  assert.equal(await bottomNav.isVisible(), false)
  assert.equal(await page.getByRole('search', { name: 'Busca mobile de NFTs' }).isVisible(), false)
  console.log('PASS Home mobile at 375/390px, compact hero, two columns, no overflow, shared search/filter/sort logic, accessible panels, real favorites with login, cart/profile links, bottom clearance and desktop visibility')
} finally {
  await browser.close()
}
