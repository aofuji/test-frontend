import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})})
const base=process.env.CHECKOUT_TEST_URL || 'http://127.0.0.1:5173'
const context=await browser.newContext()
const page=await context.newPage()
const errors=[]
page.on('pageerror',error=>errors.push(error.message))
async function reset(){
  await page.goto(base+'/')
  await page.getByRole('navigation',{name:'Navegacao principal'}).waitFor()
  const resetResponse=await page.evaluate(async()=>{const r=await fetch('/api/__mock/reset-auth',{method:'POST'}); return {status:r.status,body:await r.text(),attempt:localStorage.getItem('nft-marketplace.checkout-attempt.v1')}})
  assert.equal(resetResponse.status,200,JSON.stringify(resetResponse))
  assert.equal(JSON.parse(resetResponse.body).ok,true)
  assert.equal(resetResponse.attempt,null)
  await page.reload()
}
async function addAndLogin(){
  await page.goto(base+'/nft/aurora-001')
  await page.getByRole('button',{name:'Adicionar',exact:true}).click()
  await page.getByRole('status').filter({hasText:'NFT adicionado'}).waitFor()
  await page.goto(base+'/login?redirect=%2Fcheckout')
  await page.getByLabel('E-mail').fill('ada@example.com')
  await page.getByLabel('Senha',{exact:true}).fill('collector123')
  await page.getByRole('button',{name:'Entrar',exact:true}).click()
  await page.waitForURL(base+'/checkout')
  await page.getByRole('heading',{name:'Confirmar compra'}).waitFor()
}
async function scenario(name){
  await page.getByRole('combobox').last().click()
  await page.getByRole('option',{name}).click()
}
async function quote(){
  await page.getByRole('button',{name:'Confirmar compra'}).click()
  await page.getByRole('status').filter({hasText:'Cotacao inicial gerada'}).waitFor()
}
async function order(){await page.getByRole('button',{name:'Confirmar compra'}).click()}
async function cart(){return page.evaluate(async()=> (await (await fetch('/api/cart')).json()).cart)}
try {
  await reset()
  await addAndLogin()
  for(const width of [390,768,1440]){
    await page.setViewportSize({width,height:900})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`checkout overflow ${width}`)
  }
  await quote(); await order()
  await page.waitForURL(/\/orders\/order-/)
  await page.getByText('Confirmado',{exact:true}).first().waitFor()
  const id=page.url().split('/').pop()
  assert.ok(await page.getByText('1.2 ETH').count())
  assert.equal((await cart()).items.length,0)
  await page.reload()
  await page.getByText('Confirmado',{exact:true}).first().waitFor()
  assert.equal(page.url().split('/').pop(),id)
  console.log('PASS UI confirmed checkout, receipt, refresh, cart and 390/768/1440px')

  await reset(); await addAndLogin()
  await scenario('Timeout apos criar pedido')
  await quote(); await order()
  await page.getByRole('alert').waitFor()
  const attempt=await page.evaluate(()=>JSON.parse(localStorage.getItem('nft-marketplace.checkout-attempt.v1')))
  assert.ok(attempt.key)
  await page.reload()
  await page.waitForURL(/\/orders\/order-/)
  const recoveredId=page.url().split('/').pop()
  assert.equal((await page.evaluate(async key=> (await (await fetch('/api/orders/attempts/'+key)).json()).order.id,attempt.key)),recoveredId)
  assert.equal((await cart()).items.length,0)
  console.log('PASS UI timeout after creation recovers one order after refresh')

  await reset(); await addAndLogin()
  await scenario('Timeout antes do pedido')
  await quote(); await order()
  await page.getByRole('alert').waitFor()
  const beforeAttempt=await page.evaluate(()=>JSON.parse(localStorage.getItem('nft-marketplace.checkout-attempt.v1')))
  assert.ok(beforeAttempt.key)
  await page.reload()
  await page.getByRole('heading',{name:'Confirmar compra'}).waitFor()
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('nft-marketplace.checkout-attempt.v1')).key),beforeAttempt.key)
  await order()
  await page.waitForURL(/\/orders\/order-/)
  console.log('PASS UI timeout before creation restores quote and attempt after refresh')

  await reset(); await addAndLogin()
  await scenario('Sessao expirada')
  await quote(); await order()
  await page.waitForURL(/\/login\?redirect=/)
  const expiredAttempt=await page.evaluate(()=>JSON.parse(localStorage.getItem('nft-marketplace.checkout-attempt.v1')))
  assert.ok(expiredAttempt.key)
  await page.getByLabel('E-mail').fill('ada@example.com')
  await page.getByLabel('Senha',{exact:true}).fill('collector123')
  await page.getByRole('button',{name:'Entrar',exact:true}).click()
  await page.waitForURL(base+'/checkout')
  await page.getByRole('heading',{name:'Confirmar compra'}).waitFor()
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('nft-marketplace.checkout-attempt.v1')).key),expiredAttempt.key)
  await order()
  await page.waitForURL(/\/orders\/order-/)
  console.log('PASS UI session expiry keeps quote, wallet and attempt across login')

  await reset(); await addAndLogin()
  await scenario('Pedido pendente')
  await quote(); await order()
  await page.waitForURL(/\/orders\/order-/)
  await page.reload()
  await page.getByText('Confirmado',{exact:true}).first().waitFor({timeout:10000})
  assert.equal((await cart()).items.length,0)
  await page.goto(base+'/nft/neon-204')
  await page.getByRole('button',{name:'Adicionar',exact:true}).click()
  await page.getByRole('status').filter({hasText:'NFT adicionado'}).waitFor()
  await page.goto(base+'/checkout')
  await page.getByRole('heading',{name:'Confirmar compra'}).waitFor()
  console.log('PASS UI pending payment recovers after refresh; subsequent checkout remains available')

  await reset(); await addAndLogin()
  await scenario('Pagamento recusado')
  await quote(); await order()
  await page.getByRole('status').filter({hasText:'Pagamento recusado'}).waitFor()
  assert.equal((await cart()).items.length,1)
  await scenario('Pagamento confirmado')
  await quote(); await order()
  await page.waitForURL(/\/orders\/order-/)
  console.log('PASS UI declined retains cart and new attempt can confirm')

  await page.goto(base+'/wallets')
  await page.getByRole('heading',{name:'Gerenciamento de carteiras'}).waitFor()
  await page.getByRole('button',{name:'Editar Carteira principal'}).click()
  await page.getByText('Editar carteira',{exact:true}).waitFor()
  await page.getByRole('textbox',{name:'Apelido da carteira',exact:true}).fill('Carteira revisada')
  await page.getByRole('button',{name:'Salvar carteira'}).click()
  await page.getByRole('status').filter({hasText:'Carteira atualizada'}).waitFor()
  await page.reload()
  await page.getByText('Carteira revisada',{exact:true}).waitFor()
  console.log('PASS UI wallet edit persists after refresh')
  assert.deepEqual(errors,[])
} finally {await browser.close()}
