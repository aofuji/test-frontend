import assert from 'node:assert/strict'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
const base = process.env.AUTH_TEST_URL || 'http://127.0.0.1:5173'

async function checkLayout(page, surface, name) {
  for (const width of [375, 390]) {
    await page.setViewportSize({ width, height: 896 })
    assert.equal(await page.locator('#root > div > header').isVisible(), false)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name}: document overflow ${width}`)
    assert(await surface.evaluate((element) => element.scrollWidth <= element.clientWidth), `${name}: panel overflow ${width}`)
    assert(await surface.locator('.auth-mobile-brand').isVisible())
    assert(await surface.getByRole('button', { name: 'Continuar com Google', exact: true }).isDisabled())
    assert(await surface.getByRole('button', { name: 'Continuar com Facebook', exact: true }).isDisabled())
    await page.screenshot({ path: `/tmp/kurio-auth-${name}-${width}.png` })
  }
}

try {
  const context = await browser.newContext({ viewport: { width: 390, height: 896 } })
  const page = await context.newPage()
  await page.goto(`${base}/login?redirect=%2Fwallets`)
  const route = page.locator('.auth-route')
  await route.getByLabel('E-mail', { exact: true }).waitFor()
  await page.setViewportSize({ width: 1440, height: 1080 })
  assert(await page.locator('#root > div > header').isVisible())
  assert.equal(await route.locator('.auth-mobile-brand').isVisible(), false)
  assert.equal(await route.getByRole('button', { name: 'Mostrar senha', exact: true }).count(), 0)
  await checkLayout(page, route, 'login')
  assert(await route.getByRole('button', { name: 'Esqueceu a senha?', exact: true }).isDisabled())
  await route.getByLabel('E-mail', { exact: true }).fill('ada@example.com')
  await route.getByLabel('Senha', { exact: true }).fill('wrong-password')
  await route.getByRole('button', { name: 'Mostrar senha', exact: true }).click()
  assert.equal(await route.getByLabel('Senha', { exact: true }).getAttribute('type'), 'text')
  await route.getByRole('button', { name: 'Ocultar senha', exact: true }).click()
  const invalidLogin = page.waitForResponse((response) => response.url().endsWith('/api/auth/login'))
  await route.getByRole('button', { name: 'Entrar', exact: true }).click()
  assert.equal((await invalidLogin).status(), 401)
  await route.getByText('E-mail ou senha invalidos.', { exact: true }).waitFor()
  await route.getByLabel('Senha', { exact: true }).fill('collector123')
  await route.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.waitForURL((url) => url.pathname === '/wallets')
  await context.close()
  console.log('PASS mobile login: layout, password visibility, API error and authenticated redirect')

  const registration = await browser.newContext({ viewport: { width: 390, height: 896 } })
  const registerPage = await registration.newPage()
  await registerPage.goto(`${base}/login?redirect=%2Fwallets`)
  await registerPage.getByRole('link', { name: 'Crie uma conta', exact: true }).click()
  assert.equal(new URL(registerPage.url()).searchParams.get('redirect'), '/wallets')
  await registerPage.setViewportSize({ width: 1440, height: 1080 })
  await registerPage.getByRole('button', { name: 'Criar conta', exact: true }).waitFor()
  assert.equal(await registerPage.getByLabel('Confirmar senha', { exact: true }).count(), 0)
  await checkLayout(registerPage, registerPage.locator('.auth-route'), 'register')
  await registerPage.getByLabel('Nome', { exact: true }).fill('Mobile Collector')
  await registerPage.getByLabel('E-mail', { exact: true }).fill(`mobile-${Date.now()}@example.com`)
  await registerPage.getByLabel('Senha', { exact: true }).fill('collector123')
  await registerPage.getByLabel('Confirmar senha', { exact: true }).fill('different123')
  let registrationRequests = 0
  registerPage.on('request', (request) => { if (request.method() === 'POST' && request.url().endsWith('/api/auth/register')) registrationRequests++ })
  await registerPage.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await registerPage.getByRole('alert').filter({ hasText: 'As senhas devem ser iguais.' }).waitFor()
  assert.equal(registrationRequests, 0)
  for (const label of ['senha', 'confirmar senha']) {
    await registerPage.getByRole('button', { name: `Mostrar ${label}`, exact: true }).click()
    assert.equal(await registerPage.getByLabel(label === 'senha' ? 'Senha' : 'Confirmar senha', { exact: true }).getAttribute('type'), 'text')
    await registerPage.getByRole('button', { name: `Ocultar ${label}`, exact: true }).click()
  }
  await registerPage.getByLabel('Confirmar senha', { exact: true }).fill('collector123')
  const registerRequest = registerPage.waitForRequest((request) => request.method() === 'POST' && request.url().endsWith('/api/auth/register'))
  await registerPage.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  assert.deepEqual(Object.keys((await registerRequest).postDataJSON()).sort(), ['email', 'name', 'password'])
  await registerPage.waitForURL((url) => url.pathname === '/wallets')
  await registration.close()
  console.log('PASS mobile registration: layout, mismatch blocks API, both visibility controls, original payload and redirect')

  const modalContext = await browser.newContext({ viewport: { width: 1440, height: 1080 } })
  const modalPage = await modalContext.newPage()
  await modalPage.goto(base)
  await modalPage.getByRole('button', { name: 'Entrar', exact: true }).click()
  const dialog = modalPage.getByRole('dialog')
  assert(await dialog.getByRole('tab', { name: 'Entrar', exact: true }).isVisible())
  assert.equal(await dialog.locator('.auth-mobile-brand').isVisible(), false)
  assert.equal((await dialog.boundingBox()).width, 500)
  assert.equal((await dialog.boundingBox()).height, 600)
  await checkLayout(modalPage, dialog, 'login-modal')
  await dialog.getByRole('button', { name: 'Crie uma conta', exact: true }).click()
  await checkLayout(modalPage, dialog, 'register-modal')
  await dialog.getByRole('button', { name: 'Entre', exact: true }).click()
  await dialog.getByLabel('E-mail', { exact: true }).fill('ada@example.com')
  await dialog.getByLabel('Senha', { exact: true }).fill('collector123')
  await dialog.getByRole('button', { name: 'Entrar', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(new URL(modalPage.url()).pathname, '/')
  await modalContext.close()
  console.log('PASS existing auth modal: desktop tabs preserved, mobile layouts, switching and login close')
} finally {
  await browser.close()
}
